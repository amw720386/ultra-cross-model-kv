"""Mechanical replay of a Dockerfile as a bash script, for a box that can only start from a registry base image (Vast):
the instance runs the Dockerfile's FROM image, and this script performs every other instruction verbatim, in order.

  python h2h/gen_replay.py THEIR_REPO_DIR/Dockerfile --context /root/ot-repo --out replay.sh --map replay_map.tsv

Supported instructions (all their Dockerfile at 8f05e5f1 uses): FROM (checked, not executed), ARG, ENV, RUN, WORKDIR,
COPY, EXPOSE (recorded), ENTRYPOINT (recorded; the driver runs it). Anything else aborts, so nothing is silently
skipped. ENV/ARG values are exported AND written to /etc/ot-replay.env so the entrypoint process gets them.
replay_map.tsv: Dockerfile line number, instruction, the exact replay line(s).
"""
import argparse
import json
import shlex


def logical_lines(text):
    """Dockerfile lines with backslash continuations joined; yields (first line number, line)."""
    buf, start = [], None
    for i, raw in enumerate(text.splitlines(), 1):
        s = raw.rstrip()
        if not buf and (not s.strip() or s.strip().startswith("#")):
            continue
        if start is None:
            start = i
        if s.endswith("\\"):
            buf.append(s[:-1])
            continue
        buf.append(s)
        yield start, " ".join(x.strip() for x in buf)
        buf, start = [], None


def env_pairs(rest):
    toks = shlex.split(rest)
    if "=" not in toks[0]:  # legacy "ENV key value"
        return [(toks[0], " ".join(toks[1:]))]
    return [tuple(t.split("=", 1)) for t in toks]


def main():
    p = argparse.ArgumentParser()
    p.add_argument("dockerfile")
    p.add_argument("--context", required=True, help="their repo dir ON THE BOX (COPY sources are relative to it)")
    p.add_argument("--out", required=True)
    p.add_argument("--map", required=True)
    a = p.parse_args()
    out = ["#!/bin/bash", "# generated by h2h/gen_replay.py from their Dockerfile; every instruction below is theirs",
           "set -euo pipefail", ": > /etc/ot-replay.env", "cd /"]
    rows, meta = [], {"from": None, "expose": [], "entrypoint": None}
    for ln, line in logical_lines(open(a.dockerfile).read()):
        ins, _, rest = line.partition(" ")
        ins = ins.upper()
        rest = rest.strip()
        if ins == "FROM":
            meta["from"] = rest
            rep = [f"# FROM {rest}: the instance image itself (its digest is recorded by the driver)"]
        elif ins in ("ARG", "ENV"):
            pairs = env_pairs(rest)
            rep = []
            for k, v in pairs:
                rep += [f"export {k}={shlex.quote(v)}", f"echo {shlex.quote(k + '=' + v)} >> /etc/ot-replay.env"]
        elif ins == "RUN":
            rep = [rest]
        elif ins == "WORKDIR":
            rep = [f"mkdir -p {shlex.quote(rest)}", f"cd {shlex.quote(rest)}"]
        elif ins == "COPY":
            toks = shlex.split(rest)
            if any(t.startswith("--") for t in toks):
                raise SystemExit(f"line {ln}: COPY flags not supported: {line}")
            *srcs, dst = toks
            rep = []
            for s in srcs:
                src = f"{a.context.rstrip('/')}/{s}"
                if dst.endswith("/") or len(srcs) > 1:
                    rep.append(f"mkdir -p {shlex.quote(dst)} && cp -a {shlex.quote(src)} {shlex.quote(dst)}")
                else:
                    rep.append(f"mkdir -p \"$(dirname {shlex.quote(dst)})\" && cp -a {shlex.quote(src)} {shlex.quote(dst)}")
        elif ins == "EXPOSE":
            meta["expose"].append(rest)
            rep = [f"# EXPOSE {rest} (recorded)"]
        elif ins == "ENTRYPOINT":
            meta["entrypoint"] = json.loads(rest)
            rep = [f"# ENTRYPOINT {rest}: run by the driver as their process"]
        else:
            raise SystemExit(f"line {ln}: unsupported instruction {ins}: {line}")
        out += [f"# --- Dockerfile line {ln}: {ins}"] + rep
        rows.append(f"{ln}\t{ins}\t{line}\t" + " ;; ".join(rep))
    out.append("echo REPLAY_DONE")
    open(a.out, "w").write("\n".join(out) + "\n")
    open(a.map, "w").write("dockerfile_line\tinstruction\toriginal\treplay\n" + "\n".join(rows) + "\n")
    json.dump(meta, open(a.out + ".meta.json", "w"), indent=1)
    print(json.dumps(meta))


if __name__ == "__main__":
    main()
